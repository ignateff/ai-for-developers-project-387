import { readFileSync } from "node:fs";
import { expect, it } from "vitest";
import { parse } from "yaml";

const read = (path: string) => readFileSync(path, "utf8");
const workflow = (path: string) => parse(read(path));

const stepNamed = (job: { steps: { name?: string }[] }, name: string) => {
  const step = job.steps.find((item) => item.name === name);
  expect(step, `step ${name}`).toBeDefined();
  return step as Record<string, any>;
};

it("keeps the required CI check and admission identifiers machine-readable", () => {
  const ci = workflow(".github/workflows/ci.yml");
  expect(ci.name).toBe("CI");
  expect(Object.keys(ci.jobs)).toEqual(["check", "head-browser", "security"]);
  expect(ci.jobs.check.name).toBeUndefined();

  const command = workflow(".github/workflows/opencode.yml");
  expect(command.jobs.opencode.name).toBe(
    "opencode-command-v2-pr-${{ github.event.issue.number || github.event.pull_request.number }}",
  );
  expect(
    command.jobs.opencode.steps.some(
      (step: { name?: string }) => step.name === "Record command admission v2",
    ),
  ).toBe(true);
});

it("uses Russian display names for workflows that are safe to rename", () => {
  expect(workflow(".github/workflows/opencode.yml").name).toBe("OpenCode: команды /oc и /opencode");
  expect(workflow(".github/workflows/opencode-review.yml").name).toBe(
    "Автоматическое ревью OpenCode",
  );
  expect(workflow(".github/workflows/opencode-triage.yml").name).toBe("Автоматический триаж задач");
  expect(workflow(".github/workflows/performance-check.yml").name).toBe(
    "Проверка производительности",
  );
  expect(workflow(".github/workflows/scheduled-performance-audit.yml").name).toBe(
    "Плановый аудит производительности",
  );
  expect(workflow(".github/workflows/opencode-diagnostic.yml").name).toBe(
    "Диагностика обработчика OpenCode",
  );
  expect(workflow(".github/workflows/release-please.yml").name).toBe("Релиз release-please");
  expect(read("docs/release.md")).toContain("Релиз release-please");
});

it("publishes command failures and reasons in Russian without confirming completion", () => {
  const report = workflow(".github/workflows/opencode.yml").jobs.report.steps[0];
  expect(report.run).toContain(
    "**Команда OpenCode завершилась ошибкой. Завершение задачи НЕ подтверждено.**",
  );
  expect(report.run).toContain("Причина: %s — %s");
  expect(report.run).not.toContain("OpenCode command failed");
  expect(report.run).toContain("timeout)");
  expect(report.run).toContain("limit_exhausted)");
  expect(report.run).toContain("infra)");
  expect(report.run).toContain("agent_failed)");
  expect(report.run).toContain("неизвестная причина");
});

it("asks triage for Russian prose and an explicit Russian AI marker", () => {
  const triage = workflow(".github/workflows/opencode-triage.yml");
  const run = stepNamed(triage.jobs.triage, "Предварительный триаж");
  expect(run.env.PROMPT).toContain("Write the entire response in Russian.");
  expect(run.env.PROMPT).toContain("> *Сгенерировано ИИ в ходе триажа.*");
  expect(run.env.PROMPT).not.toContain("This was generated by AI during triage.");
  expect(run.env.PROMPT).not.toContain("Respond in the language of the issue");
});

it("requests Russian audit output and reuses existing English findings", () => {
  const manual = workflow(".github/workflows/performance-check.yml");
  expect(manual.on.workflow_dispatch.inputs.app_url.description).toContain("URL приложения");
  const run = stepNamed(manual.jobs.lighthouse, "Проанализировать с помощью OpenCode");
  const prompt = run.run.replace(/\s+/g, " ");
  expect(prompt).toContain(
    "Write every user-facing issue title, issue body, comment and summary in Russian.",
  );
  expect(prompt).toContain("Keep metric names (LCP, CLS, INP)");
  expect(prompt).toContain("search open and closed issues");
  expect(prompt).toContain("Existing findings and summaries may already be published in English");
  expect(prompt).toContain("reuse those issues and comments");
  expect(prompt).toContain("never repeat an unchanged comment");
  expect(stepNamed(manual.jobs.lighthouse, "Запустить Lighthouse").run).toContain(
    "Укажите параметр app_url или переменную репозитория APP_URL.",
  );
  expect(
    manual.jobs.lighthouse.steps.find(
      (step: { with?: { name?: string } }) => step.with?.name === "lighthouse-report",
    ),
  ).toBeDefined();
});

it("keeps the training issue title searchable across languages and closed issues", () => {
  const scheduled = workflow(".github/workflows/scheduled-performance-audit.yml");
  expect(scheduled.on.workflow_dispatch.inputs.app_url.description).toContain("URL приложения");
  expect(scheduled.on.workflow_dispatch.inputs.training.description).toContain(
    "синтетический учебный отчёт",
  );
  const run = stepNamed(scheduled.jobs.lighthouse, "Проанализировать с помощью OpenCode");
  const prompt = run.run.replace(/\s+/g, " ");
  expect(prompt).toContain('"[TRAINING] Lighthouse LCP example"');
  expect(prompt).toContain("even if closed");
  expect(prompt).toContain("fixed machine identifier");
  expect(prompt).toContain(
    "Write every user-facing issue title, issue body, comment and summary in Russian.",
  );
  expect(prompt).toContain("Existing findings and summaries may already be published in English");
  expect(prompt).toContain("reuse those issues and comments");
  expect(prompt).toContain("never repeat an unchanged comment");
  expect(prompt).toContain("Search open and closed issues");
  expect(
    scheduled.jobs.lighthouse.steps.find(
      (step: { with?: { name?: string } }) => step.with?.name === "lighthouse-report",
    ),
  ).toBeDefined();
  expect(stepNamed(scheduled.jobs.lighthouse, "Подготовить учебный отчёт").run).toContain(
    "docs/fixtures/lighthouse-training.json",
  );
});

it("keeps the existing Russian review prompt, publication and markers", () => {
  expect(read("scripts/opencode-review.ts")).toContain(
    "Write all substantive prose in Russian: summary, limitations, conditions and consequence.",
  );
  expect(read("scripts/opencode-review-publish.ts")).toContain("## Автоматическое ревью OpenCode");
  expect(read("scripts/opencode-review-publish.ts")).toContain(
    "<!-- opencode-review-report:${artifact} -->",
  );
  expect(read("scripts/opencode-budget-workflow.ts")).toContain(
    "<!-- opencode-pr-attempt-budget:v1 -->",
  );
  expect(read("scripts/opencode-budget-lock.ts")).toContain("<!-- opencode-pr-budget-lock:v1 -->");
});
