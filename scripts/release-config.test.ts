import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { parse } from "yaml";
import { expect, it } from "vitest";

it("accepts the files generated by Release Please during format checks", () => {
  const directory = mkdtempSync(join(tmpdir(), "release-format-"));
  try {
    writeFileSync(join(directory, ".oxfmtrc.json"), readFileSync(".oxfmtrc.json"));
    writeFileSync(join(directory, ".release-please-manifest.json"), '{".":"0.1.0"}\n');
    writeFileSync(join(directory, "CHANGELOG.md"), "# Changelog\n\n\n* a generated change\n");
    const result = spawnSync(resolve("node_modules/.bin/oxfmt"), ["--check", "."], {
      cwd: directory,
      encoding: "utf8",
    });
    expect(result.stderr + result.stdout).toContain("All matched files use the correct format");
    expect(result.status).toBe(0);
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
});

it("configures one application release with a versioned changelog", () => {
  const config = JSON.parse(readFileSync("release-please-config.json", "utf8"));
  const manifest = JSON.parse(readFileSync(".release-please-manifest.json", "utf8"));
  expect(Object.keys(config.packages)).toEqual(["."]);
  expect(config.packages["."]).toMatchObject({
    "release-type": "simple",
    "initial-version": "0.1.0",
    "include-component-in-tag": false,
    "include-v-in-tag": true,
  });
  const version = readFileSync("version.txt", "utf8").trim();
  expect(version).toMatch(/^\d+\.\d+\.\d+$/);
  expect(manifest["."]).toBe(version);
});

it("starts the first new-repository release after the application import", () => {
  const config = JSON.parse(readFileSync("release-please-config.json", "utf8"));
  expect(config["bootstrap-sha"]).toBe("10d74ac276471854c174b136fb70908901e5a143");
});

it("runs the same checks for push and pull requests", () => {
  const workflow = parse(readFileSync(".github/workflows/ci.yml", "utf8"));
  expect(workflow.on).toHaveProperty("push");
  expect(workflow.on).toHaveProperty("pull_request");
  expect(
    workflow.jobs.check.steps.some((step: { run?: string }) => step.run === "mise run check"),
  ).toBe(true);
});

it("uses an app-scoped token to maintain releases only on main after App configuration", () => {
  const workflow = parse(readFileSync(".github/workflows/release-please.yml", "utf8"));
  expect(workflow.on.push.branches).toEqual(["main"]);
  expect(workflow.jobs.release.if).toBe(
    "github.ref == 'refs/heads/main' && vars.RELEASE_PLEASE_APP_ID != ''",
  );
  const [app, release] = workflow.jobs.release.steps;
  expect(app.with).toMatchObject({
    "app-id": "${{ vars.RELEASE_PLEASE_APP_ID }}",
    "private-key": "${{ secrets.RELEASE_PLEASE_APP_PRIVATE_KEY }}",
    "permission-contents": "write",
    "permission-issues": "write",
    "permission-pull-requests": "write",
  });
  expect(release.with).toMatchObject({
    token: "${{ steps.app-token.outputs.token }}",
    "target-branch": "main",
  });
});
